"""Built-in unofficial default weights and the model choice shared by routes and QQ projection.

WuWa: derived from XutheringWavesUID (weights by Loping151; no licence stated), generated by
scripts/build_wuwa_default_weights.py. NTE: weights from 异环工坊 (credited as it asks;
no licence stated) with a spec measured on the role API, generated by
scripts/build_nte_default_weights.py. See THIRD_PARTY_NOTICES.md.
"""
from functools import lru_cache
from pathlib import Path
from typing import Literal
from pydantic import Field, model_validator
from .assessment import AssessmentModel, ECHO_GRADES, ECHO_GRADE_THRESHOLDS, WuwaEchoProfile
from .assessment_contracts import Contract, FiniteDecimal, WeightProfile
from .assessment_nte_math import ScoringSpec

PATH = Path(__file__).with_name('assessment-defaults-wuwa.json')
NTE_PATH = Path(__file__).with_name('assessment-defaults-nte.json')
Element = Literal['冷凝','热熔','导电','气动','衍射','湮灭']


class Provenance(Contract):
    source: Literal['XutheringWavesUID']
    repository: str
    commit: str = Field(pattern=r'^[0-9a-f]{40}$')
    path: str
    plugin_repository: str
    plugin_commit: str = Field(pattern=r'^[0-9a-f]{40}$')
    author: str
    license: Literal['unstated']
    fetched_at: str = Field(pattern=r'^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9:]{8}Z$')
    payload_sha256: str = Field(pattern=r'^[0-9a-f]{64}$')
    modified: str
    changes: str


class DefaultEntry(WuwaEchoProfile):
    name: str = Field(min_length=1,max_length=80)
    origin: Literal['xwuid_snapshot']
    upstream: str = Field(min_length=1,max_length=80)
    element: Element


class DefaultsFile(Contract):
    schema_version: Literal[1]
    formula: Literal['wuwa-echo-default-v1']
    data_version: str = Field(pattern=r'^[0-9]{4}-[0-9]{2}-[0-9]{2}(?:\.[0-9]+)?$')
    provenance: Provenance
    grade_thresholds: list[FiniteDecimal]
    grades: list[str]
    characters: dict[str,DefaultEntry]

    @model_validator(mode='after')
    def matches_formula(self):
        # The grading constants live in assessment.py; the data file must not silently disagree.
        if tuple(self.grades)!=ECHO_GRADES or tuple(self.grade_thresholds)!=ECHO_GRADE_THRESHOLDS: raise ValueError('grade table mismatch')
        if any(not k.isdigit() or e.max_main is None or e.max_sub is None for k,e in self.characters.items()): raise ValueError('character ID and maximum selection required')
        return self


class NteProvenance(Contract):
    source: Literal['异环工坊']
    endpoint: Literal['https://yh.zzzmap.com/api/open/game-character/weight-configs']
    fetched_at: str = Field(pattern=r'^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9:]{8}Z$')
    payload_sha256: str = Field(pattern=r'^[0-9a-f]{64}$')
    # The endpoint's own notice: every page showing these weights credits it.
    notice: Literal['权重配置来自：异环工坊']
    license: Literal['unstated']
    changes: str


class NteDefaultEntry(Contract):
    name: str = Field(min_length=1,max_length=80)
    substat_weights: dict[str,FiniteDecimal]
    mainstat_weights: dict[str,FiniteDecimal]


class NteDefaultsFile(Contract):
    schema_version: Literal[1]
    formula: Literal['nte-custom-weighting-v1']
    data_version: str = Field(pattern=r'^[0-9]{4}-[0-9]{2}-[0-9]{2}(?:\.[0-9]+)?$')
    provenance: NteProvenance
    spec: ScoringSpec
    characters: dict[str,NteDefaultEntry]

    @model_validator(mode='after')
    def weights_fit_spec(self):
        entries={e.canonical_id:e for e in self.spec.catalog}
        for key,entry in self.characters.items():
            if not key.isdigit(): raise ValueError('character ID required')
            if any(name not in self.spec.eligible_substats or not 0<=w<=1 for name,w in entry.substat_weights.items()): raise ValueError('substat weight outside the spec')
            if any(name not in entries or not entries[name].main or not 0<=w<=1 for name,w in entry.mainstat_weights.items()): raise ValueError('main weight outside the spec')
        return self


@lru_cache(maxsize=1)
def defaults()->DefaultsFile:
    return DefaultsFile.model_validate_json(PATH.read_text(encoding='utf-8'))


@lru_cache(maxsize=1)
def nte_defaults()->NteDefaultsFile:
    return NteDefaultsFile.model_validate_json(NTE_PATH.read_text(encoding='utf-8'))


def default_model(game,character_id)->AssessmentModel|None:
    if game=='nte':
        data=nte_defaults(); entry=data.characters.get(str(character_id))
        if entry is None: return None
        weights=WeightProfile(character_id=str(character_id),version=f'nte-workshop-{data.data_version}',source='builtin_default',
                              substat_weights=entry.substat_weights,mainstat_weights=entry.mainstat_weights)
        return AssessmentModel(game=game,character_id=str(character_id),version=f'builtin-{data.data_version}',
            source='builtin_default',attribution='nte_workshop',nte_profile=weights,nte_spec=data.spec)
    entry=defaults().characters.get(str(character_id)) if game=='wuthering_waves' else None
    if entry is None: return None
    profile=WuwaEchoProfile(main=entry.main,sub=entry.sub,max_main=entry.max_main,max_sub=entry.max_sub)
    return AssessmentModel(game=game,character_id=str(character_id),version=f'builtin-{defaults().data_version}',
        source='builtin_default',attribution=entry.origin,wuwa_echo_profile=profile)


def resolve_model(store,scope,game,character_id):
    """A saved user model wholly replaces the default; without one, the built-in default or a placeholder.

    Returns (model, origin); origin is None for the empty 'unconfigured' placeholder that
    characters without a default get. There is no fallback to the generic template.
    """
    rows=store.read(scope,game,character_id,'model') if store else []
    if rows: return AssessmentModel.model_validate(rows[0]['data']),'user_configured'
    model=default_model(game,character_id)
    if model is not None: return model,'builtin_default'
    return AssessmentModel(game=game,character_id=character_id,version='unconfigured',source='user_configured'),None

